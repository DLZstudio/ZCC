// ==================== BIOS 后端实现 ====================

CompileResult BIOSBackend::compile(const ZCCIRModule& module,
                                   const CompileOptions& options) {
    CompileResult result;
    result.success = true;
    
    try {
        // 生成汇编代码
        std::string asmCode = generateAssembly(module);
        
        // 生成引导扇区二进制
        output_ = generateBootSector(asmCode);
        
        result.binary = output_;
        
    } catch (const std::exception& e) {
        result.success = false;
        result.errorMessage = e.what();
    }
    
    return result;
}

std::string BIOSBackend::generateAssembly(const ZCCIRModule& module) {
    std::ostringstream ss;
    
    // BIOS 引导扇区汇编头
    ss << "; ZCC BIOS Boot Sector\n";
    ss << "; Generated by ZCC Compiler\n";
    ss << "; Target: x86 Real Mode (16-bit)\n\n";
    
    ss << "[bits 16]\n";
    ss << "[org 0x7C00]\n\n";
    
    ss << "; Entry point\n";
    ss << "start:\n";
    ss << "    cli                 ; Disable interrupts\n";
    ss << "    xor ax, ax          ; AX = 0\n";
    ss << "    mov ds, ax          ; DS = 0\n";
    ss << "    mov es, ax          ; ES = 0\n";
    ss << "    mov ss, ax          ; SS = 0\n";
    ss << "    mov sp, 0x7C00      ; Stack pointer\n";
    ss << "    sti                 ; Enable interrupts\n\n";
    
    // 生成 ZCC 运行时
    ss << "; ZCC Runtime\n";
    ss << "call zcc_runtime_init\n\n";
    
    // 生成主函数
    ss << "; Main function\n";
    ss << "call main\n\n";
    
    // 停机
    ss << "; Halt\n";
    ss << "hang:\n";
    ss << "    hlt\n";
    ss << "    jmp hang\n\n";
    
    // ZCC 运行时实现
    ss << "; ZCC Runtime Functions\n";
    ss << "zcc_runtime_init:\n";
    ss << "    ret\n\n";
    
    // 打印字符串函数（使用 BIOS 中断）
    ss << "; print_string(str) - Print null-terminated string\n";
    ss << "print_string:\n";
    ss << "    push si\n";
    ss << "    mov si, ax          ; String pointer in AL\n";
    ss << ".loop:\n";
    ss << "    lodsb               ; Load byte from SI to AL\n";
    ss << "    or al, al           ; Check if null\n";
    ss << "    jz .done\n";
    ss << "    mov ah, 0x0E        ; BIOS teletype function\n";
    ss << "    int 0x10            ; Call BIOS\n";
    ss << "    jmp .loop\n";
    ss << ".done:\n";
    ss << "    pop si\n";
    ss << "    ret\n\n";
    
    // 打印数字函数
    ss << "; print_number(num) - Print 16-bit number\n";
    ss << "print_number:\n";
    ss << "    ; TODO: Implement number printing\n";
    ss << "    ret\n\n";
    
    // 延迟函数
    ss << "; delay(ms) - Delay for milliseconds\n";
    ss << "delay:\n";
    ss << "    push cx\n";
    ss << "    push dx\n";
    ss << ".loop:\n";
    ss << "    mov cx, 0xFFFF\n";
    ss << ".inner:\n";
    ss << "    loop .inner\n";
    ss << "    dec ax\n";
    ss << "    jnz .loop\n";
    ss << "    pop dx\n";
    ss << "    pop cx\n";
    ss << "    ret\n\n";
    
    // 填充到 510 字节
    ss << "; Padding\n";
    ss << "times 510-($-$$) db 0\n\n";
    
    // 引导签名
    ss << "; Boot signature\n";
    ss << "dw 0xAA55\n";
    
    return ss.str();
}

std::vector<uint8_t> BIOSBackend::generateBootSector(const std::string& asmCode) {
    // 注意：这里应该调用 NASM 或其他汇编器
    // 为了演示，我们生成一个简单的引导扇区
    
    std::vector<uint8_t> bootSector(512, 0);
    
    // 简单的引导程序（直接生成机器码）
    size_t offset = 0;
    
    // cli
    bootSector[offset++] = 0xFA;
    
    // xor ax, ax
    bootSector[offset++] = 0x31;
    bootSector[offset++] = 0xC0;
    
    // mov ds, ax
    bootSector[offset++] = 0x8E;
    bootSector[offset++] = 0xD8;
    
    // mov es, ax
    bootSector[offset++] = 0x8E;
    bootSector[offset++] = 0xC0;
    
    // mov ss, ax
    bootSector[offset++] = 0x8E;
    bootSector[offset++] = 0xD0;
    
    // mov sp, 0x7C00
    bootSector[offset++] = 0xBC;
    bootSector[offset++] = 0x00;
    bootSector[offset++] = 0x7C;
    
    // sti
    bootSector[offset++] = 0xFB;
    
    // 无限循环（hlt + jmp）
    bootSector[offset++] = 0xF4;  // hlt
    bootSector[offset++] = 0xEB;  // jmp
    bootSector[offset++] = 0xFE;  // -2 (infinite loop)
    
    // 填充到 510 字节
    while (offset < 510) {
        bootSector[offset++] = 0x90;  // nop
    }
    
    // 引导签名 (0xAA55)
    bootSector[510] = 0x55;
    bootSector[511] = 0xAA;
    
    return bootSector;
}

uint8_t BIOSBackend::encodeMOV_AX_Immediate(uint16_t value) {
    // MOV AX, imm16: B8 iw
    // 返回操作码长度
    return 3;
}

uint8_t BIOSBackend::encodeINT(uint8_t num) {
    // INT imm8: CD ib
    return 2;
}

uint8_t BIOSBackend::encodeJMP_Short(int8_t offset) {
    // JMP rel8: EB cb
    return 2;
}

uint8_t BIOSBackend::encodeJMP_Far(uint16_t segment, uint16_t offset) {
    // JMP far: EA iw iw
    return 5;
}

