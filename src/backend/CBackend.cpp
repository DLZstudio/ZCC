// ==================== C 后端 ====================

CompileResult CBackend::compile(const ZCCIRModule& module,
                                const CompileOptions& options) {
    CompileResult result;
    result.success = true;
    
    try {
        output_ = generateCCode(module);
        result.output = output_;
    } catch (const std::exception& e) {
        result.success = false;
        result.errorMessage = e.what();
    }
    
    return result;
}

std::string CBackend::generateCCode(const ZCCIRModule& module) {
    std::ostringstream ss;
    
    // 文件头
    ss << "// Generated by ZCC Compiler\n";
    ss << "// Source: " << module.getMetadata().sourceFile << "\n";
    ss << "// Target: " << module.getMetadata().target.toString() << "\n\n";
    
    // 包含头文件
    ss << "#include <stdio.h>\n";
    ss << "#include <stdlib.h>\n";
    ss << "#include <stdint.h>\n";
    ss << "#include <string.h>\n\n";
    
    // 高精度类型定义
    ss << "// High precision number (string-based)\n";
    ss << "typedef struct {\n";
    ss << "    char* value;\n";
    ss << "} BigNum;\n\n";
    
    // 生成全局变量
    for (const auto& global : module.getGlobals()) {
        ss << generateGlobal(*global) << "\n";
    }
    ss << "\n";
    
    // 生成函数声明
    for (const auto& func : module.getFunctions()) {
        if (func->isExternal()) {
            ss << convertType(*func->getReturnType()) << " " 
               << func->getName() << "(";
            
            const auto& args = func->getArguments();
            for (size_t i = 0; i < args.size(); ++i) {
                if (i > 0) ss << ", ";
                ss << convertType(*args[i].second) << " " << args[i].first;
            }
            
            ss << ");\n";
        }
    }
    ss << "\n";
    
    // 生成函数定义
    for (const auto& func : module.getFunctions()) {
        if (!func->isExternal()) {
            ss << generateFunction(*func) << "\n\n";
        }
    }
    
    return ss.str();
}

std::string CBackend::generateFunction(const ZCCIRFunction& func) {
    std::ostringstream ss;
    
    // 函数签名
    ss << convertType(*func.getReturnType()) << " " << func.getName() << "(";
    
    const auto& args = func.getArguments();
    for (size_t i = 0; i < args.size(); ++i) {
        if (i > 0) ss << ", ";
        ss << convertType(*args[i].second) << " " << args[i].first;
    }
    
    ss << ") {\n";
    
    // 函数体
    indentLevel_ = 1;
    for (const auto& block : func.getBlocks()) {
        ss << generateBlock(*block);
    }
    indentLevel_ = 0;
    
    ss << "}\n";
    
    return ss.str();
}

std::string CBackend::generateBlock(const ZCCIRBlock& block) {
    std::ostringstream ss;
    
    // 块标签
    ss << indent(indentLevel_) << "// Block: " << block.getLabel() << "\n";
    
    // 指令
    for (const auto& instr : block.getInstructions()) {
        ss << indent(indentLevel_) << generateInstruction(*instr) << "\n";
    }
    
    return ss.str();
}

std::string CBackend::generateInstruction(const ZCCIRInstruction& instr) {
    std::ostringstream ss;
    
    // 辅助宏：获取操作数的名字
    auto opName = [&](size_t idx) -> std::string {
        if (idx >= instr.getNumOperands()) return "???";
        auto val = instr.getOperand(idx).getValue();
        return val ? val->getName() : "???";
    };
    
    switch (instr.getOpcode()) {
        // ========== 无操作 ==========
        case ZCCIROpcode::NOP:
            ss << "// NOP";
            break;
            
        // ========== 算术运算 ==========
        case ZCCIROpcode::ADD:
            ss << opName(0) << " = " << opName(1) << " + " << opName(2) << ";";
            break;
        case ZCCIROpcode::SUB:
            ss << opName(0) << " = " << opName(1) << " - " << opName(2) << ";";
            break;
        case ZCCIROpcode::MUL:
            ss << opName(0) << " = " << opName(1) << " * " << opName(2) << ";";
            break;
        case ZCCIROpcode::DIV:
            ss << opName(0) << " = " << opName(1) << " / " << opName(2) << ";";
            break;
        case ZCCIROpcode::MOD:
            ss << opName(0) << " = " << opName(1) << " % " << opName(2) << ";";
            break;
        case ZCCIROpcode::NEG:
            ss << opName(0) << " = -" << opName(1) << ";";
            break;
        case ZCCIROpcode::INC:
            ss << opName(0) << "++;";
            break;
        case ZCCIROpcode::DEC:
            ss << opName(0) << "--;";
            break;
        case ZCCIROpcode::POW:
            ss << opName(0) << " = pow(" << opName(1) << ", " << opName(2) << ");";
            break;
            
        // ========== 位运算 ==========
        case ZCCIROpcode::AND:
            ss << opName(0) << " = " << opName(1) << " & " << opName(2) << ";";
            break;
        case ZCCIROpcode::OR:
            ss << opName(0) << " = " << opName(1) << " | " << opName(2) << ";";
            break;
        case ZCCIROpcode::XOR:
            ss << opName(0) << " = " << opName(1) << " ^ " << opName(2) << ";";
            break;
        case ZCCIROpcode::NOT:
            ss << opName(0) << " = ~" << opName(1) << ";";
            break;
        case ZCCIROpcode::SHL:
            ss << opName(0) << " = " << opName(1) << " << " << opName(2) << ";";
            break;
        case ZCCIROpcode::SHR:
            ss << opName(0) << " = " << opName(1) << " >> " << opName(2) << ";";
            break;
            
        // ========== 比较运算 ==========
        case ZCCIROpcode::CMP_EQ:
            ss << opName(0) << " = (" << opName(1) << " == " << opName(2) << ");";
            break;
        case ZCCIROpcode::CMP_NE:
            ss << opName(0) << " = (" << opName(1) << " != " << opName(2) << ");";
            break;
        case ZCCIROpcode::CMP_LT:
            ss << opName(0) << " = (" << opName(1) << " < " << opName(2) << ");";
            break;
        case ZCCIROpcode::CMP_LE:
            ss << opName(0) << " = (" << opName(1) << " <= " << opName(2) << ");";
            break;
        case ZCCIROpcode::CMP_GT:
            ss << opName(0) << " = (" << opName(1) << " > " << opName(2) << ");";
            break;
        case ZCCIROpcode::CMP_GE:
            ss << opName(0) << " = (" << opName(1) << " >= " << opName(2) << ");";
            break;
            
        // ========== 内存操作 ==========
        case ZCCIROpcode::LOAD:
            ss << opName(0) << " = " << opName(1) << ";";
            break;
        case ZCCIROpcode::STORE:
            ss << opName(0) << " = " << opName(1) << ";";
            break;
        case ZCCIROpcode::ALLOCA:
            ss << "// ALLOCA: " << opName(0) << " = alloca(" << opName(1) << ");";
            break;
        case ZCCIROpcode::ALLOC:
            ss << opName(0) << " = malloc(" << opName(1) << ");";
            break;
        case ZCCIROpcode::FREE:
            ss << "free(" << opName(0) << ");";
            break;
            
        // ========== 类型转换 ==========
        case ZCCIROpcode::TRUNC:
        case ZCCIROpcode::ZEXT:
        case ZCCIROpcode::SEXT:
        case ZCCIROpcode::FPTRUNC:
        case ZCCIROpcode::FPEXT:
        case ZCCIROpcode::FPTOUI:
        case ZCCIROpcode::FPTOSI:
        case ZCCIROpcode::UITOFP:
        case ZCCIROpcode::SITOFP:
        case ZCCIROpcode::BITCAST:
            ss << opName(0) << " = (" << convertType(*instr.getType()) << ")" << opName(1) << ";";
            break;
            
        // ========== 控制流 ==========
        case ZCCIROpcode::CALL: {
            ss << opName(0) << " = " << opName(1) << "(";
            for (size_t i = 2; i < instr.getNumOperands(); ++i) {
                if (i > 2) ss << ", ";
                ss << opName(i);
            }
            ss << ");";
            break;
        }
        case ZCCIROpcode::RET:
            if (instr.getNumOperands() > 0) {
                ss << "return " << opName(0) << ";";
            } else {
                ss << "return;";
            }
            break;
        case ZCCIROpcode::JMP:
            ss << "goto " << opName(0) << ";";
            break;
        case ZCCIROpcode::JMP_IF:
            ss << "if (" << opName(0) << ") goto " << opName(1) << ";";
            break;
        case ZCCIROpcode::JMP_IF_NOT:
            ss << "if (!" << opName(0) << ") goto " << opName(1) << ";";
            break;
        case ZCCIROpcode::PHI:
            ss << "// PHI: " << opName(0) << " = phi(";
            for (size_t i = 1; i < instr.getNumOperands(); ++i) {
                if (i > 1) ss << ", ";
                ss << opName(i);
            }
            ss << ");";
            break;
            
        // ========== 高精度运算（调用 BigNum 运行时函数） ==========
        case ZCCIROpcode::BIG_ADD:
            ss << "bignum_add(&" << opName(0) << ", &" << opName(1) << ", &" << opName(2) << ");";
            break;
        case ZCCIROpcode::BIG_SUB:
            ss << "bignum_sub(&" << opName(0) << ", &" << opName(1) << ", &" << opName(2) << ");";
            break;
        case ZCCIROpcode::BIG_MUL:
            ss << "bignum_mul(&" << opName(0) << ", &" << opName(1) << ", &" << opName(2) << ");";
            break;
        case ZCCIROpcode::BIG_DIV:
            ss << "bignum_div(&" << opName(0) << ", &" << opName(1) << ", &" << opName(2) << ");";
            break;
        case ZCCIROpcode::BIG_MOD:
            ss << "bignum_mod(&" << opName(0) << ", &" << opName(1) << ", &" << opName(2) << ");";
            break;
        case ZCCIROpcode::BIG_CMP:
            ss << opName(0) << " = bignum_cmp(&" << opName(1) << ", &" << opName(2) << ");";
            break;
        case ZCCIROpcode::BIG_POW:
            ss << "bignum_pow(&" << opName(0) << ", &" << opName(1) << ", &" << opName(2) << ");";
            break;
            
        // ========== 字符串操作 ==========
        case ZCCIROpcode::STR_CONCAT:
            ss << opName(0) << " = str_concat(" << opName(1) << ", " << opName(2) << ");";
            break;
        case ZCCIROpcode::STR_LEN:
            ss << opName(0) << " = strlen(" << opName(1) << ");";
            break;
        case ZCCIROpcode::STR_CMP:
            ss << opName(0) << " = strcmp(" << opName(1) << ", " << opName(2) << ");";
            break;
        case ZCCIROpcode::STR_SLICE:
            ss << opName(0) << " = str_slice(" << opName(1) << ", " << opName(2) << ", " << opName(3) << ");";
            break;
            
        // ========== 数组操作 ==========
        case ZCCIROpcode::ARRAY_NEW:
            ss << opName(0) << " = zcc_array_new();";
            break;
        case ZCCIROpcode::ARRAY_GET:
            ss << opName(0) << " = zcc_array_get(" << opName(1) << ", " << opName(2) << ");";
            break;
        case ZCCIROpcode::ARRAY_SET:
            ss << "zcc_array_set(" << opName(0) << ", " << opName(1) << ", " << opName(2) << ");";
            break;
        case ZCCIROpcode::ARRAY_LEN:
            ss << opName(0) << " = zcc_array_len(" << opName(1) << ");";
            break;
            
        // ========== 对象操作 ==========
        case ZCCIROpcode::OBJECT_NEW:
            ss << opName(0) << " = zcc_object_new();";
            break;
        case ZCCIROpcode::OBJECT_GET:
            ss << opName(0) << " = zcc_object_get(" << opName(1) << ", " << opName(2) << ");";
            break;
        case ZCCIROpcode::OBJECT_SET:
            ss << "zcc_object_set(" << opName(0) << ", " << opName(1) << ", " << opName(2) << ");";
            break;
            
        // ========== 异常 ==========
        case ZCCIROpcode::THROW:
            ss << "zcc_throw(" << opName(0) << ");";
            break;
            
        // ========== 特殊操作 ==========
        case ZCCIROpcode::INTRINSIC:
            ss << "// INTRINSIC: " << opName(0);
            break;
        case ZCCIROpcode::ASSEMBLY:
            ss << "__asm__(" << escapeString(opName(0)) << ");";
            break;
        case ZCCIROpcode::TRAP:
            ss << "abort();";
            break;
        case ZCCIROpcode::UNREACHABLE:
            ss << "__builtin_unreachable();";
            break;
            
        default:
            ss << "// TODO: opcode " << static_cast<int>(instr.getOpcode());
            break;
    }
    
    return ss.str();
}

std::string CBackend::generateGlobal(const ZCCIRGlobal& global) {
    std::ostringstream ss;
    
    if (global.isConstant()) {
        ss << "const ";
    }
    
    ss << convertType(*global.getType()) << " " << global.getName();
    
    if (global.getInitializer()) {
        ss << " = " << generateExpression(
            ZCCIROperand(global.getInitializer()));
    }
    
    ss << ";";
    
    return ss.str();
}

std::string CBackend::generateExpression(const ZCCIROperand& operand) {
    if (operand.isNull()) {
        return "NULL";
    }
    
    auto value = operand.getValue();
    if (value->getKind() == ZCCIRValueKind::CONSTANT) {
        auto constant = dynamic_cast<ZCCIRConstant*>(value.get());
        if (constant) {
            return constant->toString();
        }
    }
    
    return value->getName();
}

std::string CBackend::convertType(const ZCCType& type) {
    if (type.isPrimitive()) {
        auto prim = dynamic_cast<const PrimitiveTypeImpl*>(&type);
        if (prim) {
            switch (prim->getPrimitiveType()) {
                case PrimitiveType::VOID: return "void";
                case PrimitiveType::BOOL: return "bool";
                case PrimitiveType::I8: return "int8_t";
                case PrimitiveType::I16: return "int16_t";
                case PrimitiveType::I32: return "int32_t";
                case PrimitiveType::I64: return "int64_t";
                case PrimitiveType::U8: return "uint8_t";
                case PrimitiveType::U16: return "uint16_t";
                case PrimitiveType::U32: return "uint32_t";
                case PrimitiveType::U64: return "uint64_t";
                case PrimitiveType::F32: return "float";
                case PrimitiveType::F64: return "double";
                case PrimitiveType::STRING: return "char*";
                case PrimitiveType::BIGINT:
                case PrimitiveType::BIGFLOAT:
                    return "BigNum";
                default: return "void";
            }
        }
    }
    
    if (type.isPointer()) {
        auto ptr = dynamic_cast<const PointerType*>(&type);
        if (ptr) {
            return convertType(*ptr->getPointee()) + "*";
        }
    }
    
    if (type.isArray()) {
        auto arr = dynamic_cast<const ArrayType*>(&type);
        if (arr) {
            return convertType(*arr->getElementType()) + "[]";
        }
    }
    
    return "void";
}

std::string CBackend::escapeString(const std::string& str) {
    std::ostringstream ss;
    ss << "\"";
    for (char c : str) {
        switch (c) {
            case '"': ss << "\\\""; break;
            case '\\': ss << "\\\\"; break;
            case '\n': ss << "\\n"; break;
            case '\r': ss << "\\r"; break;
            case '\t': ss << "\\t"; break;
            default: ss << c; break;
        }
    }
    ss << "\"";
    return ss.str();
}

std::string CBackend::indent(int level) {
    return std::string(level * 4, ' ');
}

