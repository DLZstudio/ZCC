// ==================== 后端管理器 ====================

BackendManager& BackendManager::getInstance() {
    static BackendManager instance;
    return instance;
}

void BackendManager::registerBackend(std::unique_ptr<Backend> backend) {
    if (backend) {
        backends_[backend->getName()] = std::move(backend);
    }
}

Backend* BackendManager::getBackend(const std::string& name) {
    auto it = backends_.find(name);
    if (it != backends_.end()) {
        return it->second.get();
    }
    return nullptr;
}

std::vector<std::string> BackendManager::getAvailableBackends() const {
    std::vector<std::string> names;
    for (const auto& [name, backend] : backends_) {
        names.push_back(name);
    }
    return names;
}

Backend* BackendManager::selectBackendForTarget(const TargetPlatform& target) {
    // 根据目标平台选择最佳后端
    if (target.isWASM()) {
        return getBackend("wasm");
    } else if (target.isMC()) {
        return getBackend("mc");
    } else if (target.isBIOS()) {
        return getBackend("bios");
    } else if (target.isMicroPython()) {
        return getBackend("micropython");
    } else {
        // 默认使用 C 后端
        return getBackend("c");
    }
}

CompileResult BackendManager::compile(const ZCCIRModule& module,
                                      const std::string& backendName,
                                      const CompileOptions& options) {
    Backend* backend = getBackend(backendName);
    if (!backend) {
        CompileResult result;
        result.success = false;
        result.errorMessage = "Backend not found: " + backendName;
        return result;
    }
    
    return backend->compile(module, options);
}

std::vector<OptimizationLevel> Backend::getSupportedOptimizations() const {
    return {
        OptimizationLevel::O0,
        OptimizationLevel::O1,
        OptimizationLevel::O2,
        OptimizationLevel::O3
    };
}

// ==================== C 后端 ====================

CompileResult CBackend::compile(const ZCCIRModule& module,
                                const CompileOptions& options) {
    CompileResult result;
    result.success = true;
    
    try {
        output_ = generateCCode(module);
        result.output = output_;
    } catch (const std::exception& e) {
        result.success = false;
        result.errorMessage = e.what();
    }
    
    return result;
}

std::string CBackend::generateCCode(const ZCCIRModule& module) {
    std::ostringstream ss;
    
    // 文件头
    ss << "// Generated by ZCC Compiler\n";
    ss << "// Source: " << module.getMetadata().sourceFile << "\n";
    ss << "// Target: " << module.getMetadata().target.toString() << "\n\n";
    
    // 包含头文件
    ss << "#include <stdio.h>\n";
    ss << "#include <stdlib.h>\n";
    ss << "#include <stdint.h>\n";
    ss << "#include <string.h>\n\n";
    
    // 高精度类型定义
    ss << "// High precision number (string-based)\n";
    ss << "typedef struct {\n";
    ss << "    char* value;\n";
    ss << "} BigNum;\n\n";
    
    // 生成全局变量
    for (const auto& global : module.getGlobals()) {
        ss << generateGlobal(*global) << "\n";
    }
    ss << "\n";
    
    // 生成函数声明
    for (const auto& func : module.getFunctions()) {
        if (func->isExternal()) {
            ss << convertType(func->getReturnType()) << " " 
               << func->getName() << "(";
            
            const auto& args = func->getArguments();
            for (size_t i = 0; i < args.size(); ++i) {
                if (i > 0) ss << ", ";
                ss << convertType(*args[i].second) << " " << args[i].first;
            }
            
            ss << ");\n";
        }
    }
    ss << "\n";
    
    // 生成函数定义
    for (const auto& func : module.getFunctions()) {
        if (!func->isExternal()) {
            ss << generateFunction(*func) << "\n\n";
        }
    }
    
    return ss.str();
}

std::string CBackend::generateFunction(const ZCCIRFunction& func) {
    std::ostringstream ss;
    
    // 函数签名
    ss << convertType(func.getReturnType()) << " " << func.getName() << "(";
    
    const auto& args = func.getArguments();
    for (size_t i = 0; i < args.size(); ++i) {
        if (i > 0) ss << ", ";
        ss << convertType(*args[i].second) << " " << args[i].first;
    }
    
    ss << ") {\n";
    
    // 函数体
    indentLevel_ = 1;
    for (const auto& block : func.getBlocks()) {
        ss << generateBlock(*block);
    }
    indentLevel_ = 0;
    
    ss << "}\n";
    
    return ss.str();
}

std::string CBackend::generateBlock(const ZCCIRBlock& block) {
    std::ostringstream ss;
    
    // 块标签
    ss << indent(indentLevel_) << "// Block: " << block.getLabel() << "\n";
    
    // 指令
    for (const auto& instr : block.getInstructions()) {
        ss << indent(indentLevel_) << generateInstruction(*instr) << "\n";
    }
    
    return ss.str();
}

std::string CBackend::generateInstruction(const ZCCIRInstruction& instr) {
    std::ostringstream ss;
    
    switch (instr.getOpcode()) {
        case ZCCIROpcode::NOP:
            ss << "; // NOP";
            break;
            
        case ZCCIROpcode::ADD:
            ss << instr.getOperand(0).getValue()->getName() << " = "
               << instr.getOperand(1).getValue()->getName() << " + "
               << instr.getOperand(2).getValue()->getName() << ";";
            break;
            
        case ZCCIROpcode::SUB:
            ss << instr.getOperand(0).getValue()->getName() << " = "
               << instr.getOperand(1).getValue()->getName() << " - "
               << instr.getOperand(2).getValue()->getName() << ";";
            break;
            
        case ZCCIROpcode::MUL:
            ss << instr.getOperand(0).getValue()->getName() << " = "
               << instr.getOperand(1).getValue()->getName() << " * "
               << instr.getOperand(2).getValue()->getName() << ";";
            break;
            
        case ZCCIROpcode::DIV:
            ss << instr.getOperand(0).getValue()->getName() << " = "
               << instr.getOperand(1).getValue()->getName() << " / "
               << instr.getOperand(2).getValue()->getName() << ";";
            break;
            
        case ZCCIROpcode::LOAD:
            ss << instr.getOperand(0).getValue()->getName() << " = *"
               << instr.getOperand(1).getValue()->getName() << ";";
            break;
            
        case ZCCIROpcode::STORE:
            ss << "*" << instr.getOperand(0).getValue()->getName() << " = "
               << instr.getOperand(1).getValue()->getName() << ";";
            break;
            
        case ZCCIROpcode::CALL:
            ss << instr.getOperand(0).getValue()->getName() << " = "
               << instr.getOperand(1).getValue()->getName() << "(";
            for (size_t i = 2; i < instr.getNumOperands(); ++i) {
                if (i > 2) ss << ", ";
                ss << instr.getOperand(i).getValue()->getName();
            }
            ss << ");";
            break;
            
        case ZCCIROpcode::RET:
            if (instr.getNumOperands() > 0) {
                ss << "return " << instr.getOperand(0).getValue()->getName() << ";";
            } else {
                ss << "return;";
            }
            break;
            
        case ZCCIROpcode::JMP:
            ss << "goto " << instr.getOperand(0).getValue()->getName() << ";";
            break;
            
        case ZCCIROpcode::JMP_IF:
            ss << "if (" << instr.getOperand(0).getValue()->getName() << ") "
               << "goto " << instr.getOperand(1).getValue()->getName() << ";";
            break;
            
        case ZCCIROpcode::BIG_ADD:
            ss << "bignum_add(&" << instr.getOperand(0).getValue()->getName()
               << ", &" << instr.getOperand(1).getValue()->getName()
               << ", &" << instr.getOperand(2).getValue()->getName() << ");";
            break;
            
        default:
            ss << "// TODO: Implement opcode " << static_cast<int>(instr.getOpcode());
            break;
    }
    
    return ss.str();
}

std::string CBackend::generateGlobal(const ZCCIRGlobal& global) {
    std::ostringstream ss;
    
    if (global.isConstant()) {
        ss << "const ";
    }
    
    ss << convertType(global.getType()) << " " << global.getName();
    
    if (global.getInitializer()) {
        ss << " = " << generateExpression(
            ZCCIROperand(global.getInitializer()));
    }
    
    ss << ";";
    
    return ss.str();
}

std::string CBackend::generateExpression(const ZCCIROperand& operand) {
    if (operand.isNull()) {
        return "NULL";
    }
    
    auto value = operand.getValue();
    if (value->getKind() == ZCCIRValueKind::CONSTANT) {
        auto constant = dynamic_cast<ZCCIRConstant*>(value.get());
        if (constant) {
            return constant->toString();
        }
    }
    
    return value->getName();
}

std::string CBackend::convertType(const ZCCType& type) {
    if (type.isPrimitive()) {
        auto prim = dynamic_cast<const PrimitiveTypeImpl*>(&type);
        if (prim) {
            switch (prim->getPrimitiveType()) {
                case PrimitiveType::VOID: return "void";
                case PrimitiveType::BOOL: return "bool";
                case PrimitiveType::I8: return "int8_t";
                case PrimitiveType::I16: return "int16_t";
                case PrimitiveType::I32: return "int32_t";
                case PrimitiveType::I64: return "int64_t";
                case PrimitiveType::U8: return "uint8_t";
                case PrimitiveType::U16: return "uint16_t";
                case PrimitiveType::U32: return "uint32_t";
                case PrimitiveType::U64: return "uint64_t";
                case PrimitiveType::F32: return "float";
                case PrimitiveType::F64: return "double";
                case PrimitiveType::STRING: return "char*";
                case PrimitiveType::BIGINT:
                case PrimitiveType::BIGFLOAT:
                    return "BigNum";
                default: return "void";
            }
        }
    }
    
    if (type.isPointer()) {
        auto ptr = dynamic_cast<const PointerType*>(&type);
        if (ptr) {
            return convertType(*ptr->getPointee()) + "*";
        }
    }
    
    if (type.isArray()) {
        auto arr = dynamic_cast<const ArrayType*>(&type);
        if (arr) {
            return convertType(*arr->getElementType()) + "[]";
        }
    }
    
    return "void";
}

std::string CBackend::escapeString(const std::string& str) {
    std::ostringstream ss;
    ss << "\"";
    for (char c : str) {
        switch (c) {
            case '"': ss << "\\\""; break;
            case '\\': ss << "\\\\"; break;
            case '\n': ss << "\\n"; break;
            case '\r': ss << "\\r"; break;
            case '\t': ss << "\\t"; break;
            default: ss << c; break;
        }
    }
    ss << "\"";
    return ss.str();
}

std::string CBackend::indent(int level) const {
    return std::string(level * 4, ' ');
}

